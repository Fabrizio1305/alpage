let courante = 'fr';

/**
 * Langue à utiliser : le choix explicite s'il est connu, sinon la première langue du
 * téléphone que le jeu connaît, sinon l'anglais.
 */
export function choisirLangue(preference, languesNavigateur = []) {
  if (LANGUES.includes(preference)) return preference;
  for (const l of languesNavigateur) {
    const code = String(l).toLowerCase().split('-')[0];
    if (LANGUES.includes(code)) return code;
  }
  return 'en';
}

export function definirLangue(langue) {
  courante = LANGUES.includes(langue) ? langue : 'fr';
}

export const langueCourante = () => courante;

/** Texte traduit ; les entrées avec paramètres sont des fonctions. */
export function t(cle, ...args) {
  const v = TEXTES[courante][cle] ?? TEXTES.fr[cle];
  if (v === undefined) return cle;
  return typeof v === 'function' ? v(...args) : v;
}

/** Applique les traductions aux éléments marqués `data-i18n` et `data-i18n-aria`. */
export function traduirePage(racine = document) {
  for (const el of racine.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of racine.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
  document.documentElement.lang = courante;
}

